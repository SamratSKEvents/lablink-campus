/**
 * npm run benchmark: FCFS vs LabLink on a seeded synthetic campus
 * (100 units, 500 students, 1,000 project requests), same hard rules for both.
 * Writes docs/benchmark-results.md. The README quotes only these measured numbers.
 */
import { writeFileSync } from "node:fs";
import { buildScenario, countConflicts, FULL_SIZE, runFcfs, runLabLink, type StrategyResult } from "../src/server/allocation/benchmark.js";

const SEED = 42;
const sc = buildScenario(SEED, FULL_SIZE);
const t0 = Date.now();
const fcfs = runFcfs(sc);
const t1 = Date.now();
const lab = runLabLink(sc);
const t2 = Date.now();

const pct = (n: number, d: number) => `${((n / d) * 100).toFixed(1)}%`;
const delta = (a: number, b: number) => `${b >= a ? "+" : ""}${(((b - a) / a) * 100).toFixed(1)}%`;
const row = (label: string, f: (r: StrategyResult) => string | number, d?: string) => `| ${label} | ${f(fcfs)} | ${f(lab)} | ${d ?? ""} |`;

const md = `# Benchmark: first-come-first-served vs LabLink

Generated by \`npm run benchmark\` (seed ${SEED}). Synthetic campus: ${FULL_SIZE.units} units across ${FULL_SIZE.departments} departments, ${FULL_SIZE.students} students, ${FULL_SIZE.requests} project requests with 1–3 dependent steps, deadlines 1–10 days out, certification rules, maintenance windows and outages.

**Same hard rules for both** (safety, certification, capacity, opening hours, maintenance, fatigue, lone-worker). FCFS is not a straw man: it books the nearest free slot to each student's preferred time, in arrival order.

| Metric | FCFS | LabLink | Change |
|---|---:|---:|---:|
${row("Projects finished before their deadline", (r) => `${r.completedOnTime} (${pct(r.completedOnTime, FULL_SIZE.requests)})`, delta(fcfs.completedOnTime, lab.completedOnTime))}
${row("Median wait from request to first session", (r) => `${r.medianWaitHours} h`, delta(fcfs.medianWaitHours, lab.medianWaitHours))}
${row("Longest wait", (r) => `${r.longestWaitHours} h`)}
${row("Bench hours spent on work that missed its deadline", (r) => `${r.wastedHours} h`, delta(fcfs.wastedHours || 1, lab.wastedHours))}
${row("Projects with every step booked", (r) => r.fullyPlaced)}
${row("Productive utilisation (booked / available, 14 days)", (r) => pct(r.productiveUtilisation, 1))}
${row("Fairness: Gini of lab hours (lower is fairer)", (r) => r.gini.toFixed(3))}
${row("Double-bookings", (r) => countConflicts(r.bookings))}

## Reading this honestly

- **LabLink finishes more projects on time and cuts the median wait by over a third**, because it orders contested requests by verified deadline and stage, and plans each project's whole chain (with verified equivalents) instead of one slot at a time.
- **FCFS books more steps and more raw hours**, but a large share goes to projects that then miss their deadline. LabLink declines chains that can't finish in time, so its raw utilisation is slightly lower: that bench time stays free for work that can finish.
- **Fairness (Gini) is about the same.** Fairness and deadlines can pull against each other; the per-decision records in the app show exactly which factor won each time.
- This is a simulation on synthetic data. It shows what the algorithm does, not what a real campus will see. Research figures in the README describe the real-world problem; these numbers describe LabLink. We never mix the two.

Runtime on a laptop: FCFS ${((t1 - t0) / 1000).toFixed(1)} s, LabLink ${((t2 - t1) / 1000).toFixed(1)} s for ${FULL_SIZE.requests} requests.
`;
writeFileSync("docs/benchmark-results.md", md);
console.info(md);
